# Recoverable cleanup of obsolete standalone S4 experiment entrypoints only.
# Never follows junctions, never deletes payloads, never changes current G bundle.
$ErrorActionPreference = 'Stop'
$repoPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$archiveParent = Join-Path $repoPath '.archive'
if ((Test-Path -LiteralPath $archiveParent) -and ((Get-Item -LiteralPath $archiveParent -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
    throw 'Archive parent is a junction; refusing cross-volume cleanup.'
}
$archivePath = Join-Path $archiveParent '2026_10_19_baseline_G_controls'
if (Test-Path -LiteralPath $archivePath) { throw 'Archive exists; inspect its manifest, do not repeat.' }
$targets = @(
    'drive_upload/AnchorFlow_S4_FineAblation_30ep_A100',
    'drive_upload/AnchorFlow_S4_JPIR_26ep_A100',
    'drive_upload/AnchorFlow_S4_NoFine_30ep_A100',
    'drive_upload/AnchorFlow_S4_UPIR_30ep_A100',
    'drive_upload/AnchorFlow_S4_TRT_Recovery',
    'drive_upload/AnchorFlow_S4_FineAblation_30ep_A100.zip',
    'drive_upload/AnchorFlow_S4_JPIR_26ep_A100.zip',
    'drive_upload/AnchorFlow_S4_NoFine_30ep_A100.zip',
    'drive_upload/AnchorFlow_S4_UPIR_30ep_A100.zip',
    'scripts/package_s4_fine_ablation.py', 'scripts/verify_s4_fine_ablation.py',
    'scripts/package_s4_jpir.py', 'scripts/verify_s4_jpir.py',
    'scripts/package_s4_nofine.py', 'scripts/verify_s4_nofine.py',
    'scripts/package_s4_upir.py', 'scripts/verify_s4_upir.py',
    'scripts/package_s4_upir_norel.py', 'scripts/verify_s4_upir_norel.py'
)
$records = @()
foreach ($relative in $targets) {
    $sourcePath = [IO.Path]::GetFullPath((Join-Path $repoPath $relative))
    $destPath = [IO.Path]::GetFullPath((Join-Path $archivePath $relative))
    if (-not $sourcePath.StartsWith($repoPath + '\') -or -not $destPath.StartsWith($archivePath + '\')) {
        throw "Invalid resolved scope: $sourcePath -> $destPath"
    }
    if (-not (Test-Path -LiteralPath $sourcePath)) { throw "Missing target: $sourcePath" }
    $item = Get-Item -LiteralPath $sourcePath -Force
    if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Junction: $sourcePath" }
    if ($item.PSIsContainer) {
        $nested = @(Get-ChildItem -LiteralPath $sourcePath -Recurse -Force)
        if (@($nested | Where-Object { $_.Attributes -band [IO.FileAttributes]::ReparsePoint }).Count) {
            throw "Nested junction: $sourcePath"
        }
        $files = @($nested | Where-Object { -not $_.PSIsContainer })
    } else { $files = @($item) }
    $tracked = @(& git -C $repoPath ls-files -- $relative)
    if ($tracked.Count) { throw "Tracked target requires separate review: $relative" }
    $entries = @($files | ForEach-Object {
        [ordered]@{path=$_.FullName.Substring($repoPath.Length+1).Replace('\','/');
                  bytes=$_.Length;sha256=(Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLower()}
    })
    $records += [ordered]@{source=$relative;destination=$destPath;files=$entries}
}
New-Item -ItemType Directory -Path $archivePath -Force | Out-Null
foreach ($record in $records) {
    $sourcePath = [IO.Path]::GetFullPath((Join-Path $repoPath $record.source))
    $destPath = [IO.Path]::GetFullPath($record.destination)
    # Exact targets were fully audited above; no paths generated by a second shell.
    New-Item -ItemType Directory -Path (Split-Path -Parent $destPath) -Force | Out-Null
    Move-Item -LiteralPath $sourcePath -Destination $destPath
    foreach ($entry in $record.files) {
        $movedPath = Join-Path $archivePath $entry.path
        if ((Get-FileHash -LiteralPath $movedPath -Algorithm SHA256).Hash.ToLower() -ne $entry.sha256) {
            throw "Post-move verification failed: $movedPath"
        }
    }
}
$result = [ordered]@{date='2026-10-19';operation='recoverable move, no deletion';
    archive_root=$archivePath;external_D_available=(Test-Path -LiteralPath 'D:\');
    current_baseline_untouched=$true;items=$records}
$json = $result | ConvertTo-Json -Depth 8
$json | Set-Content -LiteralPath (Join-Path $archivePath 'restore_manifest.json') -Encoding UTF8
$json | Set-Content -LiteralPath (Join-Path $repoPath 'benchmarks/s4_upir_norel_2026_10_19/cleanup_manifest.json') -Encoding UTF8
Write-Output "Archived $($records.Count) exact targets, verified SHA256. Restore paths recorded in $archivePath"
